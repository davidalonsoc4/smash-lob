test("manual groups stay balanced and draft seed changes must be applied before starting",async({page})=>{
  const fixture=await installTraditionalFixture(page,"groups_knockout")
  await page.goto("/tournaments/new")
  await page.getByRole("combobox",{name:"Modalidad",exact:true}).selectOption("traditional")
  await page.getByRole("combobox",{name:"Formato",exact:true}).selectOption("groups_knockout")
  for(let i=0;i<12;i++)await page.getByLabel(`Jugador ${i+1}`,{exact:true}).fill(`Seed ${i+1}`)
  await page.getByText("Sorteo y cabezas de serie",{exact:true}).click()
  await page.getByRole("button",{name:"Aumentar Cabezas de serie",exact:true}).click()
  await page.getByRole("button",{name:"Bajar pareja: Seed 1 / Seed 2",exact:true}).click()
  await page.getByRole("checkbox",{name:"Asignar grupos manualmente",exact:true}).check()
  const groups=await page.getByRole("combobox",{name:/^Grupo: Seed/}).all(),first=await groups[0].inputValue()
  const other=groups[(await Promise.all(groups.map(group=>group.inputValue()))).findIndex(value=>value!==first)]
  const opposite=await other.inputValue()
  await groups[0].selectOption(opposite)
  await expect(page.getByRole("button",{name:"Crear y generar calendario",exact:true})).toBeDisabled()
  await other.selectOption(first)
  await page.getByRole("button",{name:"Crear y generar calendario",exact:true}).click()
  await expect(page).toHaveURL(new RegExp(`/tournaments/${id}/calendar$`))
  expect(fixture.data().traditional.draw.seedOrder[0]).toBe("pair-2")
  expect(fixture.data().traditional.draw.groups.map(group=>group.teamIds.length)).toEqual([3,3])
  await page.getByText("Sorteo y cabezas de serie",{exact:true}).click()
  await page.getByRole("button",{name:"Aumentar Cabezas de serie",exact:true}).click()
  await expect(page.getByRole("button",{name:"Iniciar torneo",exact:true})).toBeDisabled()
  await page.getByRole("button",{name:"Volver a sortear",exact:true}).click()
  await expect(page.getByRole("button",{name:"Iniciar torneo",exact:true})).toBeEnabled()
})

