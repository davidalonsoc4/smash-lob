import { readFile } from "node:fs/promises"
import { describe, expect, it } from "vitest"

const read = (path: string) => readFile(path, "utf8")

describe("match detail pairing panel", () => {
  it("keeps the pending versus view but promotes a vertical result layout when scores exist", async () => {
    const [panel, leaguePage, personalPage, personalServer, personalModel, personalDetailModel, sharedView] = await Promise.all([
      read("src/components/match/MatchDetailPairingPanel.tsx"),
      read("src/app/match/[id]/page.tsx"),
      read("src/app/personal-matches/[id]/page.tsx"),
      read("src/lib/serverPersonalMatches.ts"),
      read("src/lib/personalMatches.ts"),
      read("src/lib/personalMatchDetailModel.ts"),
      read("src/components/match/MatchDetailView.tsx"),
    ])

    expect(panel).not.toContain(">\n          Emparejamiento\n        </h2>")
    expect(panel).toContain('const hasResult = sets.length > 0 || (pointsA !== null && pointsB !== null)')
    expect(panel).toContain('<FinishedPairRow')
    expect(panel).toContain('function FinishedPairRow({')
    expect(panel).not.toContain('alignment: "left" | "right"\n  showAvatars: boolean')
    expect(panel).not.toContain('showAvatars={showAvatars}')
    expect(panel).toContain('app-match-result-head col-span-full grid')
    expect(panel).toContain('app-match-result-surface grid gap-x-1 rounded-2xl border bg-white')
    expect(panel).toContain('gridTemplateColumns: "subgrid"')
    expect(panel).not.toContain('rounded-xl bg-white px-2.5 py-2 ring-1 ring-neutral-200')
    expect(panel).not.toContain('shrink-0 rounded-xl bg-white px-2 py-2 ring-1 ring-neutral-200')
    expect(panel).toContain('import { SetGameScore } from "@/components/matches/SetGameScore"')
    expect(panel).toContain('<SetGameScore value={ownScore} won={ownScore > rivalScore} />')
    expect(panel).not.toContain('type-caption font-bold uppercase tracking-wide text-neutral-400')
    expect(panel).toContain('function FinishedPlayerName({')
    expect(panel).toContain('metadataPlacement: "before-name" | "after-name"')
    expect(panel).toContain('metadataPlacement="after-name"')
    expect(panel).not.toContain("<PlayerAvatar")
    expect(panel).toContain('showRankingPosition && position ? `#${position}` : null')
    expect(panel).toContain('.filter(Boolean).join(" · ")')
    expect(panel).toContain("{metadataLine}")
    expect(panel).toContain("<FitText noWrap minFontSize={10}")
    expect(panel).not.toContain('positionPlacement: "above" | "below"')
    expect(panel).toContain('side="a"')
    expect(panel).toContain('side="b"')
    expect(panel).not.toContain('mb-1.5 text-left type-caption font-bold uppercase leading-none tracking-wide text-neutral-500')
    expect(panel).not.toContain('mt-1.5 text-left type-caption font-bold uppercase leading-none tracking-wide text-neutral-500')
    expect(panel).not.toContain('bg-neutral-100 font-black text-neutral-800 ring-neutral-200')
    expect(panel).not.toContain('bg-neutral-50 font-bold text-neutral-500 ring-neutral-200')
    expect(panel).toContain('app-match-result-total relative text-3xl font-black leading-none tabular-nums')
    expect(panel).not.toContain('label={tx("Pareja A")}')
    expect(panel).not.toContain('label={tx("Pareja B")}')
    expect(panel).toContain('alignment === "right" ? "flex-row-reverse"')
    expect(panel).toContain('type-player-name-prominent')
    expect(panel).not.toContain('line-clamp-2')
    expect(panel).not.toContain('[overflow-wrap:anywhere]')
    expect(panel).toContain('truncate whitespace-nowrap type-player-name-prominent')
    expect(panel).toContain('`#${position}`')
    const finishedPlayer = panel.slice(panel.indexOf("function FinishedPlayerName({"), panel.indexOf("function FinishedPairRow({"))
    expect(finishedPlayer).toContain("getPreferredPlayerSideLabel")
    expect(finishedPlayer).toContain("getDominantHandLabel")
    expect(finishedPlayer).toContain("showPlayerMetadata && playerPositionLabel")
    expect(finishedPlayer).not.toContain("en liga")
    expect(panel).toContain('alignment="left"')
    expect(panel).toContain('alignment="right"')
    expect(panel).toContain('className="min-w-0 text-left"')
    expect(panel).toContain('alignment === "right" ? "text-right" : "text-left"')
    expect(panel).not.toContain('type-caption font-bold uppercase leading-none tracking-wide')
    expect(panel).not.toContain('mr-auto flex h-7 min-w-7')
    expect(panel).not.toContain('ml-auto flex h-7 min-w-7')
    expect(panel).toContain('points !== null && points !== undefined')
    expect(panel).toContain('grid grid-cols-2 items-stretch gap-3')
    expect(panel).toContain('relative grid grid-cols-2 items-stretch gap-3')
    expect(panel).toContain('pointer-events-none absolute left-1/2 top-1/2 z-20')
    expect(panel).toContain('>\n                  VS\n                </span>')
    expect(panel).toContain('flex h-9 w-9 items-center justify-center rounded-full bg-neutral-950 type-caption font-black uppercase tracking-wide text-white shadow-sm')
    expect(panel).toContain('app-match-result-set flex items-center justify-center')
    expect(panel).toContain('app-match-pair-surface rounded-xl border border-neutral-200 bg-white px-3 py-4')
    expect(panel).toContain('border-t border-neutral-300')
    expect(panel).toContain('alignment === "right" ? "ml-4" : "mr-4"')
    expect(panel).toContain('className={index === 0 ? "flex items-end pb-2" : "flex items-start pt-2"}')
    expect(panel).toContain('app-match-result-divider relative mr-2 h-px')
    expect(panel).not.toContain('className="grid grid-cols-2 items-start gap-2 sm:gap-4"')
    expect(panel).toContain('className="relative grid grid-cols-2 items-stretch gap-3"')
    expect(panel).toContain('pointer-events-none absolute left-1/2 top-1/2 z-20')

    expect(leaguePage).toContain("<MatchDetailView")
    expect(sharedView).toContain("<MatchDetailPairingPanel")
    expect(leaguePage).toContain("getRankingDisplayPosition(rankingPlayers, playerId)")
    expect(leaguePage).not.toContain("getRankingPosition(rankingPlayers, playerId)")
    expect(leaguePage).toContain("rankingPositions,")
    expect(leaguePage).not.toContain("<MatchScoreboard")

    expect(personalPage).toContain("<MatchDetailView")
    expect(personalPage).toContain("linkPlayers: false")
    expect(personalPage).toContain("showPendingPlayerMetadata: true")
    expect(personalPage).toContain("showFinishedPlayerMetadata: false")
    expect(personalPage).toContain("buildPersonalMatchDetailModel(item)")
    expect(personalDetailModel).toContain("avatarUrl: participant.avatarUrl ?? null")
    expect(personalDetailModel).toContain("preferredSide: participant.preferredSide ?? null")
    expect(personalDetailModel).toContain("dominantHand: participant.dominantHand ?? null")
    expect(sharedView).toContain("items-center justify-between")
    expect(sharedView).toContain("<MatchStatusBadge")
    expect(personalPage).not.toContain("<MatchScoreboard")

    expect(personalModel).toContain("avatarUrl?: string | null")
    expect(personalModel).toContain('preferredSide?: "drive" | "reves" | "versatile" | null')
    expect(personalModel).toContain('dominantHand?: "right" | "left" | null')
    expect(personalServer).toContain('.from("app_users")')
    expect(personalServer).toContain('.select("id,avatar_url,preferred_side,dominant_hand")')
    expect(personalServer).toContain("accountMetadataByUserId")
  })
})
