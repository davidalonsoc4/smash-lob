function decodeJsxEntities(value: string) {
  return value
    .replaceAll("&amp;", "&")
    .replaceAll("&quot;", '\"')
    .replaceAll("&#39;", "'")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
}

function flattenDictionary(
  source: DictionaryRecord,
  target: DictionaryRecord,
  result: Map<string, string>,
) {
  Object.entries(source).forEach(([key, sourceValue]) => {
    const targetValue = target[key]

    if (typeof sourceValue === "string" && typeof targetValue === "string") {
      result.set(decodeJsxEntities(sourceValue), targetValue)
      return
    }

    if (
      sourceValue &&
      targetValue &&
      typeof sourceValue === "object" &&
      typeof targetValue === "object" &&
      !Array.isArray(sourceValue) &&
      !Array.isArray(targetValue)
    ) {
      flattenDictionary(
        sourceValue as DictionaryRecord,
        targetValue as DictionaryRecord,
        result,
      )
    }
  })
}

function buildDictionaryValueMap(locale: Exclude<Locale, "es">) {
  const result = new Map<string, string>()
  flattenDictionary(
    es as unknown as DictionaryRecord,
    (locale === "en" ? en : eu) as unknown as DictionaryRecord,
    result,
  )
  return result
}

const DICTIONARY_VALUES = {
  en: buildDictionaryValueMap("en"),
  eu: buildDictionaryValueMap("eu"),
}

function buildTemplateRegExp(sourceTemplate: string) {
  const escaped = sourceTemplate
    .split("{}")
    .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("(.*?)")
  return new RegExp(`^${escaped}$`)
}

const COMPILED_DYNAMIC_TEMPLATES = {
  en: DYNAMIC_TEMPLATES.en.map(([source, target]) => [
    buildTemplateRegExp(source),
    target,
  ] as const),
  eu: DYNAMIC_TEMPLATES.eu.map(([source, target]) => [
    buildTemplateRegExp(source),
    target,
  ] as const),
}

function interpolateIndexedTemplate(
  targetTemplate: string,
  captures: string[],
  locale: Exclude<Locale, "es">,
): string {
  return targetTemplate.replace(/\{(\d+)\}/g, (_match, rawIndex: string) => {
    const value = captures[Number(rawIndex)] ?? ""
    return translateLeagueText(locale, value)
  })
}

export function translateLeagueText(locale: Locale, rawSource: string): string {
  const source = decodeJsxEntities(rawSource)

  if (locale === "es" || !source) {
    return source
  }

  const finalOverride = FINAL_OVERRIDES[locale][
    source as keyof (typeof FINAL_OVERRIDES)[typeof locale]
  ]
  if (typeof finalOverride === "string") {
    return finalOverride
  }

  const additionalOverride = ADDITIONAL_OVERRIDES[locale][
    source as keyof (typeof ADDITIONAL_OVERRIDES)[typeof locale]
  ]
  if (typeof additionalOverride === "string") {
    return additionalOverride
  }

  const exactOverride = EXACT_OVERRIDES[locale][
    source as keyof (typeof EXACT_OVERRIDES)[typeof locale]
  ]
  if (typeof exactOverride === "string") {
    return exactOverride
  }

  const dictionaryValue = DICTIONARY_VALUES[locale].get(source)
  if (dictionaryValue) {
    return dictionaryValue
  }

  for (const [pattern, formatter] of SPECIAL_RULES[locale]) {
    const match = source.match(pattern)
    if (match) {
      return (formatter as (...captures: string[]) => string)(...match.slice(1))
    }
  }

  for (const [pattern, targetTemplate] of COMPILED_DYNAMIC_TEMPLATES[locale]) {
    const match = source.match(pattern)
    if (match) {
      return interpolateIndexedTemplate(targetTemplate, match.slice(1), locale)
    }
  }

  return source
}

export function getIntlLocale(locale: Locale) {
  if (locale === "en") return "en-GB"
  if (locale === "eu") return "eu-ES"
  return "es-ES"
}
